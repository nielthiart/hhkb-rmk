// VIAL_KEYBOARD_DEF and VIAL_KEYBOARD_ID, generated by build.rs from vial.json.
include!(concat!(env!("OUT_DIR"), "/config_generated.rs"));

bind_interrupts!(struct Irqs {
    USBD => usb::InterruptHandler<USBD>;
    SAADC => saadc::InterruptHandler;
    RNG => rng::InterruptHandler<RNG>;
    EGU0_SWI0 => nrf_sdc::mpsl::LowPrioInterruptHandler;
    CLOCK_POWER => nrf_sdc::mpsl::ClockInterruptHandler, usb::vbus_detect::InterruptHandler;
    RADIO => nrf_sdc::mpsl::HighPrioInterruptHandler;
    TIMER0 => nrf_sdc::mpsl::HighPrioInterruptHandler;
    RTC0 => nrf_sdc::mpsl::HighPrioInterruptHandler;
});

/// Hold Esc and Backspace to unlock Vial's matrix tester.
const UNLOCK_KEYS: &[(u8, u8)] = &[(0, 0), (1, 13)];

const L2CAP_TXQ: u8 = 3;
const L2CAP_RXQ: u8 = 3;
const L2CAP_MTU: u16 = 251;

const LFCLK: mpsl::raw::mpsl_clock_lfclk_cfg_t = mpsl::raw::mpsl_clock_lfclk_cfg_t {
    source: mpsl::raw::MPSL_CLOCK_LF_SRC_RC as u8,
    rc_ctiv: mpsl::raw::MPSL_RECOMMENDED_RC_CTIV as u8,
    rc_temp_ctiv: mpsl::raw::MPSL_RECOMMENDED_RC_TEMP_CTIV as u8,
    accuracy_ppm: 500,
    skip_wait_lfclk_started: mpsl::raw::MPSL_DEFAULT_SKIP_WAIT_LFCLK_STARTED != 0,
};

#[embassy_executor::main]
async fn main(spawner: Spawner) {
    let mut config = embassy_nrf::config::Config::default();
    // REG0 stays on its LDO, as in ZMK's nice_nano_v2 board file.
    config.dcdc.reg1 = true;
    let p = embassy_nrf::init(config);
    // Embassy leaves the flash instruction cache off; code runs several times slower without it.
    pac::NVMC.icachecnf().write(|w| w.set_cacheen(true));
    let core = cortex_m::Peripherals::take().expect("core peripherals are only taken here");

    static MPSL: StaticCell<MultiprotocolServiceLayer> = StaticCell::new();
    static SESSION_MEM: StaticCell<mpsl::SessionMem<1>> = StaticCell::new();
    let mpsl_p =
        mpsl::Peripherals::new(p.RTC0, p.TIMER0, p.TEMP, p.PPI_CH19, p.PPI_CH30, p.PPI_CH31);
    let mpsl: &'static MultiprotocolServiceLayer = MPSL.init(
        MultiprotocolServiceLayer::with_timeslots(
            mpsl_p,
            Irqs,
            LFCLK,
            SESSION_MEM.init(mpsl::SessionMem::new()),
        )
        .expect("MPSL should start with this clock config"),
    );
    spawner.spawn(mpsl_task(mpsl).expect("the MPSL task is only spawned once"));
    let sdc_p = sdc::Peripherals::new(
        p.PPI_CH17, p.PPI_CH18, p.PPI_CH20, p.PPI_CH21, p.PPI_CH22, p.PPI_CH23, p.PPI_CH24,
        p.PPI_CH25, p.PPI_CH26, p.PPI_CH27, p.PPI_CH28, p.PPI_CH29,
    );
    let mut rng = rng::Rng::new(p.RNG, Irqs);
    let mut sdc_mem = sdc::Mem::<4696>::new();
    let sdc = build_sdc(sdc_p, &mut rng, mpsl, &mut sdc_mem)
        .expect("the controller config should be valid");

    let mut matrix = HhkbMatrix::new(
        matrix::Pins {
            power: p.P1_06.into(),
            key: p.P1_04.into(),
            hys: p.P0_11.into(),
            strobe: p.P0_06.into(),
            bits: [
                p.P1_00.into(),
                p.P0_24.into(),
                p.P0_22.into(),
                p.P0_20.into(),
                p.P0_17.into(),
                p.P0_08.into(),
            ],
        },
        core.DCB,
        core.DWT,
    );

    // The nice!nano v2 battery feeds VDDH directly, so read VDDH/5.
    interrupt::SAADC.set_priority(interrupt::Priority::P3);
    let saadc = saadc::Saadc::new(
        p.SAADC,
        Irqs,
        saadc::Config::default(),
        [saadc::ChannelConfig::single_ended(
            saadc::VddhDiv5Input.degrade_saadc(),
        )],
    );
    saadc.calibrate().await;
    let mut battery_adc = NrfAdc::new(
        saadc,
        [AnalogEventType::Battery],
        [0],
        Duration::from_secs(30),
        None,
    );
    let mut battery = BatteryProcessor::new(1, 5);

    let rmk_config = RmkConfig {
        device_config: DeviceConfig {
            vid: 0x4c4b,
            pid: 0x4848,
            manufacturer: "Niel",
            product_name: "HHKB Pro2",
            ..DeviceConfig::default()
        },
        vial_config: VialConfig::new(VIAL_KEYBOARD_ID, VIAL_KEYBOARD_DEF, UNLOCK_KEYS),
        ble_battery_config: BleBatteryConfig::default(),
        storage_config: StorageConfig {
            start_addr: 0xA0000,
            num_sectors: 6,
            ..StorageConfig::default()
        },
    };

    let mut keymap_data = KeymapData::<ROWS, COLS, LAYERS, 0>::new(keymap::default_keymap());
    let mut behavior_config = BehaviorConfig::default();
    let positional_config = PositionalConfig::default();
    let (keymap, mut storage) = initialize_keymap_and_storage(
        &mut keymap_data,
        Flash::take(mpsl, p.NVMC),
        &rmk_config.storage_config,
        &mut behavior_config,
        &positional_config,
    )
    .await;

    let mut keyboard = Keyboard::new(&keymap);
    let host_service = HostService::new(&keymap, &rmk_config);
    let usb_driver = Driver::new(p.USBD, Irqs, HardwareVbusDetect::new(Irqs));
    let mut usb =
        UsbTransport::new(usb_driver, rmk_config.device_config).with_host_service(&host_service);
    let mut ble = BleTransport::new(sdc, ble_addr(), rmk_config).with_host_service(&host_service);
    let mut watchdog = Nrf52Watchdog::default_runner(p.WDT);

    run_all!(
        matrix,
        battery_adc,
        storage,
        usb,
        ble,
        battery,
        keyboard,
        watchdog
    )
    .await;
}

#[embassy_executor::task]
async fn mpsl_task(mpsl: &'static MultiprotocolServiceLayer<'static>) -> ! {
    mpsl.run().await
}

fn build_sdc<'d, const N: usize>(
    p: nrf_sdc::Peripherals<'d>,
    rng: &'d mut rng::Rng<Async>,
    mpsl: &'d MultiprotocolServiceLayer,
    mem: &'d mut sdc::Mem<N>,
) -> Result<nrf_sdc::SoftdeviceController<'d>, nrf_sdc::Error> {
    sdc::Builder::new()?
        .support_adv()
        .support_peripheral()
        .support_dle_peripheral()
        .support_phy_update_peripheral()
        .support_le_2m_phy()
        .peripheral_count(1)?
        .buffer_cfg(L2CAP_MTU, L2CAP_MTU, L2CAP_TXQ, L2CAP_RXQ)?
        .build(p, rng, mpsl, mem)
}

/// A random static address from the chip's unique ID. The top two bits set
/// mark it as static.
fn ble_addr() -> [u8; 6] {
    let id =
        (u64::from(pac::FICR.deviceid(1).read()) << 32) | u64::from(pac::FICR.deviceid(0).read());
    let [b0, b1, b2, b3, b4, b5, ..] = (id | 0xC000_0000_0000).to_le_bytes();
    [b0, b1, b2, b3, b4, b5]
}

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    cortex_m::peripheral::SCB::sys_reset()
}
